import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const page=fs.readFileSync('output/VLA_详细图解讲义.html','utf8');
const script=page.match(/<script>([\s\S]*?)<\/script>/)[1];
const values={b:4,dp:4,g:8,n:96000,hz:50,h:50,s:20,lat:200};
const nodes=Object.fromEntries(Object.entries(values).map(([k,v])=>[k,{value:String(v),addEventListener(){}}]));
nodes.batchout={};nodes.rtcout={};
const context={document:{getElementById:id=>nodes[id],querySelectorAll:()=>Object.values(nodes).filter(n=>n.addEventListener)}};
vm.createContext(context);vm.runInContext(script,context);
assert.match(nodes.batchout.textContent,/128/);assert.match(nodes.batchout.textContent,/750.00/);
assert.match(nodes.rtcout.textContent,/10 个控制步/);assert.match(nodes.rtcout.textContent,/满足/);
nodes.lat.value='800';vm.runInContext('update()',context);assert.match(nodes.rtcout.textContent,/不够/);
nodes.s.value='55';vm.runInContext('update()',context);assert.match(nodes.rtcout.textContent,/检查输入/);
nodes.b.value='0';vm.runInContext('update()',context);assert.match(nodes.batchout.textContent,/正整数/);
const ids=new Set([...page.matchAll(/id="([^"]+)"/g)].map(m=>m[1]));
for(const m of page.matchAll(/href="#([^"]+)"/g))assert.ok(ids.has(m[1]),`missing ${m[1]}`);
assert.equal([...page.matchAll(/<figure><img src="data:image\/png;base64/g)].length,18);
console.log('HTML checks passed: calculators, invalid inputs, 22 navigation targets, 18 embedded images.');
